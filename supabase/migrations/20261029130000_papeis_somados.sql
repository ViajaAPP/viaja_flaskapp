create table if not exists public.user_role_grant (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id bigint not null references public."user"(user_id) on delete cascade,
  role public.user_role not null,
  status text not null default 'PENDING' check (status in ('PENDING', 'APPROVED', 'REJECTED')),
  cnpj text,
  review_note text,
  reviewed_by bigint references public."user"(user_id),
  reviewed_at timestamptz,
  unique (user_id, role)
);

alter table public.user_role_grant enable row level security;
